CREATE TABLE IF NOT EXISTS besti_recruitment_window (
    id BIGSERIAL PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    opens_at TIMESTAMPTZ NOT NULL,
    closes_at TIMESTAMPTZ NOT NULL,
    term VARCHAR(50) NOT NULL,
    member_start DATE NOT NULL,
    member_end DATE NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT false,
    version INTEGER NOT NULL DEFAULT 1,
    created_by BIGINT NOT NULL REFERENCES users(user_id),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (closes_at > opens_at), CHECK (member_end >= member_start)
);
CREATE TABLE IF NOT EXISTS besti_team_application (
    id BIGSERIAL PRIMARY KEY,
    window_id BIGINT NOT NULL REFERENCES besti_recruitment_window(id),
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    real_name VARCHAR(100) NOT NULL,
    student_number VARCHAR(50) NOT NULL,
    school_name VARCHAR(200) NOT NULL,
    motivation TEXT NOT NULL,
    experience TEXT NOT NULL DEFAULT '',
    contact VARCHAR(160) NOT NULL,
    gender VARCHAR(30) NOT NULL DEFAULT '',
    political_status VARCHAR(50) NOT NULL DEFAULT '',
    email VARCHAR(254) NOT NULL DEFAULT '',
    campus_rank VARCHAR(160) NOT NULL DEFAULT '',
    learning_content TEXT NOT NULL DEFAULT '',
    student_work TEXT NOT NULL DEFAULT '',
    platform_accounts TEXT NOT NULL DEFAULT '',
    weekly_hours INTEGER CHECK (weekly_hours BETWEEN 1 AND 80),
    status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','withdrawn')),
    review_note TEXT NOT NULL DEFAULT '',
    reviewed_by BIGINT REFERENCES users(user_id),
    reviewed_at TIMESTAMPTZ,
    member_id BIGINT REFERENCES association_member(member_id) ON DELETE SET NULL,
    version INTEGER NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (window_id,user_id)
);
CREATE INDEX IF NOT EXISTS idx_besti_application_review ON besti_team_application(window_id,status,id);
