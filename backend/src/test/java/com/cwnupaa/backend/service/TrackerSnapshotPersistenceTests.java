package com.cwnupaa.backend.service;

import com.baomidou.mybatisplus.extension.spring.MybatisSqlSessionFactoryBean;
import com.cwnupaa.backend.mapper.OjPracticeRecordMapper;
import com.cwnupaa.backend.mapper.OjUserAccountMapper;
import org.apache.ibatis.session.SqlSessionFactory;
import org.junit.jupiter.api.*;
import org.mybatis.spring.annotation.MapperScan;
import org.springframework.context.annotation.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;

import javax.sql.DataSource;
import java.util.*;
import java.util.concurrent.*;

import static org.assertj.core.api.Assertions.*;

class TrackerSnapshotPersistenceTests {
    private AnnotationConfigApplicationContext context;
    private JdbcTemplate jdbc;
    private TrackerSnapshotService snapshots;

    @BeforeEach
    void setup() {
        context = new AnnotationConfigApplicationContext(Config.class);
        jdbc = context.getBean(JdbcTemplate.class);
        jdbc.execute("DROP ALL OBJECTS");
        jdbc.execute("CREATE TABLE oj_user_account (user_id BIGINT PRIMARY KEY, codeforces_id VARCHAR(100), atcoder_id VARCHAR(100), newcoder_id VARCHAR(100), luogu_id VARCHAR(100), luogu_client_id TEXT, cwnuoj_id VARCHAR(100), qoj_id VARCHAR(100), ucup_id VARCHAR(100), qoj_cookie TEXT)");
        jdbc.execute("CREATE TABLE oj_practice_record (practice_problem_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL, source_id BIGINT NOT NULL, problem_id VARCHAR(100) NOT NULL, problem_name VARCHAR(200) NOT NULL, problem_difficulty VARCHAR(50), problem_tag TEXT, ac_time TIMESTAMP NOT NULL, UNIQUE(user_id, source_id, problem_id))");
        jdbc.update("INSERT INTO oj_user_account (user_id, codeforces_id, atcoder_id, newcoder_id, luogu_id) VALUES (1, 'test', 'test', '123', '123')");
        jdbc.update("INSERT INTO oj_user_account (user_id, codeforces_id) VALUES (2, 'test')");
        snapshots = context.getBean(TrackerSnapshotService.class);
    }

    @AfterEach
    void cleanup() { context.close(); }

    private Map<String, Object> row(String id, long time) {
        return Map.of("problem_id", id, "title", id, "solve_time", time, "difficulty", 800, "tags", List.of("math"));
    }

    private int count(long user, long source) {
        return jdbc.queryForObject("SELECT COUNT(*) FROM oj_practice_record WHERE user_id=? AND source_id=?", Integer.class, user, source);
    }

    @Test
    void duplicatesCountOnceAndBackfillCorrectsTheFirstAcInShanghaiTime() {
        assertThat(snapshots.reconcile(1L, 1L, "CodeForces", "test", List.of(row("CF1A", 100)))).isEqualTo(1);
        assertThat(snapshots.reconcile(1L, 1L, "CodeForces", "test", List.of(row("CF1A", 200), row("CF1A", 10), row("CF1B", 30)))).isEqualTo(1);
        assertThat(count(1, 1)).isEqualTo(2);
        assertThat(jdbc.queryForObject("SELECT ac_time FROM oj_practice_record WHERE user_id=1 AND problem_id='CF1A'", java.sql.Timestamp.class).toLocalDateTime())
                .isEqualTo(java.time.LocalDateTime.of(1970, 1, 1, 8, 0, 10));
    }

    @Test
    void reconcilesStalePlatformRecordsWithoutTouchingOtherUsersOrSchoolOj() {
        snapshots.reconcile(1L, 1L, "CodeForces", "test", List.of(row("CFold", 10)));
        snapshots.reconcile(2L, 1L, "CodeForces", "test", List.of(row("CFother", 10)));
        jdbc.update("INSERT INTO oj_practice_record (user_id, source_id, problem_id, problem_name, ac_time) VALUES (1, 5, 'P1', 'School', CURRENT_TIMESTAMP)");
        snapshots.reconcile(1L, 1L, "CodeForces", "test", List.of(row("CFnew", 20)));
        assertThat(count(1, 1)).isEqualTo(1);
        assertThat(count(2, 1)).isEqualTo(1);
        assertThat(count(1, 5)).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT problem_id FROM oj_practice_record WHERE user_id=1 AND source_id=1", String.class)).isEqualTo("CFnew");
    }

    @Test
    void aFailedDatabaseWriteRollsBackAllChanges() {
        snapshots.reconcile(1L, 1L, "CodeForces", "test", List.of(row("CFold", 10)));
        Map<String, Object> invalid = new HashMap<>(row("CFbad", 20));
        invalid.put("title", "x".repeat(201));
        assertThatThrownBy(() -> snapshots.reconcile(1L, 1L, "CodeForces", "test", List.of(row("CFnew", 20), invalid)))
                .isInstanceOf(RuntimeException.class);
        assertThat(count(1, 1)).isEqualTo(1);
        assertThat(jdbc.queryForObject("SELECT problem_id FROM oj_practice_record WHERE user_id=1", String.class)).isEqualTo("CFold");
    }

    @Test
    void changedBindingDoesNotMixOldAndNewAccounts() {
        snapshots.reconcile(1L, 1L, "CodeForces", "test", List.of(row("CFold", 10)));
        jdbc.update("UPDATE oj_user_account SET codeforces_id='new' WHERE user_id=1");
        assertThatThrownBy(() -> snapshots.reconcile(1L, 1L, "CodeForces", "test", List.of(row("CFnew", 20))))
                .hasMessageContaining("绑定账号发生变化");
        assertThat(count(1, 1)).isEqualTo(1);
    }

    @Test
    void simultaneousSyncsCannotCreateDuplicateProblems() throws Exception {
        try (var pool = Executors.newFixedThreadPool(2)) {
            var ready = new CountDownLatch(2);
            var start = new CountDownLatch(1);
            Callable<Integer> sync = () -> {
                ready.countDown();
                start.await(3, TimeUnit.SECONDS);
                return snapshots.reconcile(1L, 1L, "CodeForces", "test", List.of(row("CF1A", 10), row("CF1B", 20)));
            };
            var a = pool.submit(sync);
            var b = pool.submit(sync);
            assertThat(ready.await(3, TimeUnit.SECONDS)).isTrue();
            start.countDown();
            assertThat(a.get(5, TimeUnit.SECONDS) + b.get(5, TimeUnit.SECONDS)).isEqualTo(2);
        }
        assertThat(count(1, 1)).isEqualTo(2);
    }

    @Test
    void missingOptionalMetadataDoesNotEraseKnownDifficulty() {
        snapshots.reconcile(1L, 1L, "CodeForces", "test", List.of(row("CF1A", 10)));
        snapshots.reconcile(1L, 1L, "CodeForces", "test", List.of(Map.of("problem_id", "CF1A", "solve_time", 10L)));
        assertThat(jdbc.queryForObject("SELECT problem_difficulty FROM oj_practice_record", String.class)).isEqualTo("800");
        assertThat(jdbc.queryForObject("SELECT problem_tag FROM oj_practice_record", String.class)).isEqualTo("math");
    }

    @Test
    void qojAndUcupSnapshotsStayIsolatedAndRequireTheCurrentBinding() {
        jdbc.update("UPDATE oj_user_account SET qoj_id='test',ucup_id='ucup-team123' WHERE user_id=1");
        assertThat(snapshots.reconcile(1L,6L,"QOJ","test",List.of(row("QOJ42",10)))).isEqualTo(1);
        assertThat(snapshots.reconcile(1L,7L,"UCup","ucup-team123",List.of(row("QOJ42",20),row("QOJ43",30)))).isEqualTo(2);
        assertThat(count(1,6)).isEqualTo(1);
        assertThat(count(1,7)).isEqualTo(2);
        jdbc.update("UPDATE oj_user_account SET ucup_id='ucup-team456' WHERE user_id=1");
        assertThatThrownBy(() -> snapshots.reconcile(1L,7L,"UCup","ucup-team123",List.of())).hasMessageContaining("绑定账号发生变化");
        assertThat(count(1,7)).isEqualTo(2);
    }

    @Configuration
    @EnableTransactionManagement(proxyTargetClass = true)
    @MapperScan("com.cwnupaa.backend.mapper")
    static class Config {
        @Bean DataSource dataSource() {
            return new DriverManagerDataSource("jdbc:h2:mem:tracker_snapshot;MODE=PostgreSQL;DATABASE_TO_LOWER=TRUE;DB_CLOSE_DELAY=-1", "sa", "");
        }
        @Bean SqlSessionFactory sqlSessionFactory(DataSource dataSource) throws Exception {
            var factory = new MybatisSqlSessionFactoryBean();
            factory.setDataSource(dataSource);
            return factory.getObject();
        }
        @Bean JdbcTemplate jdbcTemplate(DataSource source) { return new JdbcTemplate(source); }
        @Bean PlatformTransactionManager transactionManager(DataSource source) { return new DataSourceTransactionManager(source); }
        @Bean TrackerSnapshotService trackerSnapshotService(OjPracticeRecordMapper records, OjUserAccountMapper accounts) {
            return new TrackerSnapshotService(records, accounts);
        }
    }
}
