package com.cwnupaa.backend.service;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.time.LocalDate;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

class TeamMembershipServiceTests {
    private JdbcTemplate db;
    private TeamMembershipService membership;
    private final LocalDate today = LocalDate.of(2026, 11, 11);

    @BeforeEach void setup() {
        db = new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", ""));
        db.execute("CREATE TABLE users(user_id bigint PRIMARY KEY, account_status varchar(30))");
        db.execute("CREATE TABLE association_member(member_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id bigint, department varchar(80), position varchar(80), term varchar(40), start_date date, end_date date)");
        db.update("INSERT INTO users VALUES(7,'normal'),(8,'pending'),(9,'banned')");
        membership = new TeamMembershipService(db);
    }

    private void add(Long user, String department, String position, String term, LocalDate start, LocalDate end) {
        db.update("INSERT INTO association_member(user_id,department,position,term,start_date,end_date) VALUES(?,?,?,?,?,?)", user, department, position, term, start, end);
    }

    @Test void verifiedStudentAloneIsNotATeamMember() {
        assertFalse(membership.isCurrentMember(7L, today));
        assertFalse(membership.isCurrentMember(null, today));
    }

    @Test void onlyExplicitlyBoundCurrentTeamPositionsQualify() {
        add(null, "ACM 校队", "队员", "2026-2027学年", null, null);
        add(7L, "科学之光技术联盟", "社团负责人", "2026-2027学年", null, null);
        add(7L, "计算机工程师联盟", "负责人", "2026-2027学年", null, null);
        add(7L, "ACM 校队", "自称队员", "2026-2027学年", null, null);
        assertFalse(membership.isCurrentMember(7L, today));
        add(7L, "ACM 校队", "队员", "2026-2027学年", null, null);
        assertTrue(membership.isCurrentMember(7L, today));
    }

    @Test void datesIncludeStartAndEndButNotFutureOrExpiredTerms() {
        add(7L, "ACM 校队", "校队队长", "2026-2027学年", today, today.plusDays(1));
        assertFalse(membership.isCurrentMember(7L, today.minusDays(1)));
        assertTrue(membership.isCurrentMember(7L, today));
        assertTrue(membership.isCurrentMember(7L, today.plusDays(1)));
        assertFalse(membership.isCurrentMember(7L, today.plusDays(2)));
    }

    @Test void invalidOrMissingDatesNeverGrantEligibility() {
        add(7L, "ACM 校队", "队员", "无届别", null, null);
        add(7L, "ACM 校队", "队员", "2027-2026学年", null, null);
        add(7L, "ACM 校队", "队员", "2026-2027学年", today.plusDays(1), today.minusDays(1));
        assertFalse(membership.isCurrentMember(7L, today));
    }

    @Test void rejectedUnverifiedOrBannedAccountsRemainExcluded() {
        add(8L, "ACM 校队", "队员", "2026-2027学年", null, null);
        add(9L, "ACM 校队", "队员", "2026-2027学年", null, null);
        assertFalse(membership.isCurrentMember(8L, today));
        assertFalse(membership.isCurrentMember(9L, today));
    }

    @Test void unlinkRemovalAndStatusChangesTakeEffectWithoutCachedSessions() {
        add(7L, "ACM 校队", "队员", "2026-2027学年", null, null);
        assertTrue(membership.isCurrentMember(7L, today));
        db.update("UPDATE association_member SET user_id=NULL");
        assertFalse(membership.isCurrentMember(7L, today));
        db.update("UPDATE association_member SET user_id=7");
        db.update("UPDATE users SET account_status='banned' WHERE user_id=7");
        assertFalse(membership.isCurrentMember(7L, today));
        db.update("UPDATE users SET account_status='normal' WHERE user_id=7");
        assertTrue(membership.isCurrentMember(7L, today));
        db.update("DELETE FROM association_member");
        assertFalse(membership.isCurrentMember(7L, today));
    }
}
