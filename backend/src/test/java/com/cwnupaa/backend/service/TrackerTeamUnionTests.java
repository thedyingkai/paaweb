package com.cwnupaa.backend.service;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import java.nio.file.Files;
import java.nio.file.Path;
import static org.assertj.core.api.Assertions.*;

class TrackerTeamUnionTests {
    private JdbcTemplate db;
    @BeforeEach void setup() throws Exception {
        db = new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:union;MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", ""));
        db.execute("DROP ALL OBJECTS");
        db.execute("CREATE TABLE users(user_id BIGINT PRIMARY KEY, account_status VARCHAR(20))");
        db.execute("CREATE TABLE team(team_id BIGINT PRIMARY KEY)");
        db.execute("CREATE TABLE team_member(team_id BIGINT, member_id BIGINT, status VARCHAR(1))");
        db.execute("CREATE TABLE oj_practice_record(practice_problem_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT, source_id BIGINT, problem_id VARCHAR(100), problem_name VARCHAR(200), problem_difficulty VARCHAR(20), problem_tag TEXT, ac_time TIMESTAMP)");
        String migration = Files.readString(Path.of("../SQL/migration_besti_tracker_team.sql"));
        String views = migration.substring(migration.indexOf("CREATE OR REPLACE VIEW"), migration.lastIndexOf("COMMIT;"));
        for (String sql : views.split(";")) if (!sql.isBlank()) db.execute(sql);
        db.update("INSERT INTO users VALUES (1,'normal'),(2,'normal'),(3,'normal'),(4,'normal'),(5,'normal')");
        db.update("INSERT INTO team VALUES (1),(2)");
        db.update("INSERT INTO team_member VALUES (1,1,'1'),(1,2,'1'),(1,3,'0'),(2,2,'1'),(2,4,'1')");
        add(1,1,"CF1A","2026-11-12 10:00:00");
        add(2,1,"CF1A","2026-11-10 10:00:00");
        add(2,1,"CF1B","2026-11-11 10:00:00");
        add(3,1,"pending","2026-11-11 10:00:00");
        add(4,1,"indirect","2026-11-11 10:00:00");
        add(5,1,"unrelated","2026-11-11 10:00:00");
    }
    private void add(long user,long source,String pid,String time) {
        db.update("INSERT INTO oj_practice_record(user_id,source_id,problem_id,problem_name,ac_time) VALUES (?,?,?,?,CAST(? AS TIMESTAMP))",user,source,pid,pid,time);
    }
    private java.util.List<String> problems(long user) {
        return db.queryForList("SELECT problem_id FROM oj_effective_practice_record WHERE user_id=? ORDER BY problem_id",String.class,user);
    }
    @Test void onlyDirectConfirmedTeammatesAreMergedWithoutDuplicateProblems() {
        assertThat(problems(1)).containsExactly("CF1A","CF1B");
        assertThat(problems(2)).containsExactly("CF1A","CF1B","indirect");
        assertThat(problems(3)).containsExactly("pending");
        assertThat(problems(5)).containsExactly("unrelated");
    }
    @Test void firstAcTimeIsStableAcrossDuplicateDays() {
        assertThat(db.queryForObject("SELECT ac_time FROM oj_effective_practice_record WHERE user_id=1 AND problem_id='CF1A'",java.sql.Timestamp.class).toLocalDateTime())
                .isEqualTo(java.time.LocalDateTime.of(2026,11,10,10,0));
        assertThat(db.queryForObject("SELECT COUNT(*) FROM oj_effective_practice_record WHERE user_id=1 AND ac_time >= TIMESTAMP '2026-11-12 00:00:00'",Integer.class)).isZero();
    }
    @Test void qojAndUcupShareProblemIdentityButOtherJudgesDoNot() {
        add(1,6,"QOJ42","2026-11-10 10:00:00"); add(2,7,"QOJ42","2026-11-11 10:00:00");
        add(2,7,"QOJ43","2026-11-11 10:00:00"); add(1,2,"CF1A","2026-11-11 10:00:00");
        assertThat(problems(1)).hasSize(5);
        assertThat(db.queryForObject("SELECT COUNT(*) FROM oj_effective_practice_record WHERE user_id=1 AND source_id=6",Integer.class)).isEqualTo(2);
    }
    @Test void acceptingLeavingOrDisbandingChangesTheViewWithoutCopyingRows() {
        long raw = db.queryForObject("SELECT COUNT(*) FROM oj_practice_record",Long.class);
        db.update("UPDATE team_member SET status='1' WHERE team_id=1 AND member_id=3");
        assertThat(problems(1)).contains("pending");
        db.update("DELETE FROM team_member WHERE team_id=1 AND member_id=2");
        assertThat(problems(1)).doesNotContain("CF1B");
        db.update("DELETE FROM team WHERE team_id=1");
        assertThat(problems(1)).containsExactly("CF1A");
        assertThat(db.queryForObject("SELECT COUNT(*) FROM oj_practice_record",Long.class)).isEqualTo(raw);
    }
    @Test void aSuspendedMemberDoesNotShareRecords() {
        db.update("UPDATE users SET account_status='banned' WHERE user_id=2");
        assertThat(problems(1)).containsExactly("CF1A");
        assertThat(problems(2)).containsExactly("CF1A","CF1B");
    }
    @Test void multipleSharedTeamsCannotDuplicateAContributor() {
        db.update("INSERT INTO team_member VALUES (2,1,'1'),(1,2,'1')");
        assertThat(problems(1)).containsExactly("CF1A","CF1B","indirect");
    }
}
